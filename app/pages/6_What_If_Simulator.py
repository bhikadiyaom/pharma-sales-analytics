"""What-if simulator for price, promotion, lead time and demand surge."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import plotly.graph_objects as go  # noqa: E402
import streamlit as st  # noqa: E402

from src.config import category_assumptions  # noqa: E402
from src.inventory.whatif import Scenario, simulate  # noqa: E402
from src.viz.app_data import cfg, data_badge, fmt_money, page_setup, result, sidebar_filters  # noqa: E402
from src.viz.theme import ACCENT, PRIMARY, style_fig  # noqa: E402

page_setup("What-If Simulator", "🧪")
_, cats = sidebar_filters()
st.title("🧪 What-If Simulator")
data_badge()
st.caption(
    "Change price, promotion, lead time or demand and see the effect on revenue and required stock. "
    "Price elasticity is an **assumption** (editable); results are scenario estimates, not forecasts."
)

inv = cfg()["inventory"]
best = result("best_models.csv").set_index("category")
fb = result("forecasts_best.parquet")

# preset buttons set slider state before the widgets are created
presets = {
    "Epidemic (+30 % demand)": dict(surge=30),
    "Supply delay (+4 d lead time)": dict(lt=4),
    "10 % discount + promo": dict(price=-10, promo=20),
    "Reset": dict(),
}
for _k in ("w_price", "w_promo", "w_surge", "w_lt"):
    st.session_state.setdefault(_k, 0)
cols = st.columns(len(presets))
for col, (name, vals) in zip(cols, presets.items()):
    if col.button(name, width="stretch"):
        st.session_state.update(
            w_price=vals.get("price", 0),
            w_promo=vals.get("promo", 0),
            w_surge=vals.get("surge", 0),
            w_lt=vals.get("lt", 0),
        )

left, right = st.columns([1, 2])
with left:
    cat = st.selectbox("Category", cats)
    price = st.slider(
        "Price change (%)", -30, 30, key="w_price", help="Demand responds via the assumed price elasticity."
    )
    promo = st.slider(
        "Promotion uplift (%)", 0, 100, key="w_promo", help="Extra demand generated by a promotion."
    )
    surge = st.slider(
        "Demand surge (%)", -30, 100, key="w_surge", help="Exogenous shock, e.g. epidemic +30 %."
    )
    lt = st.slider(
        "Lead-time change (days)", -3, 14, key="w_lt", help="Supplier delay (+) or faster delivery (−)."
    )
    el = st.number_input(
        "Assumed price elasticity",
        -3.0,
        0.0,
        float(inv["price_elasticity"]),
        0.1,
        help="−0.6 means a 10 % price rise lowers demand by 6 %.",
    )
    sl = st.radio(
        "Service level", inv["service_levels"], index=1, format_func=lambda x: f"{x:.0%}", horizontal=True
    )

a = category_assumptions(cfg(), cat)
f = fb[fb["category"] == cat].sort_values("h")["yhat"].to_numpy()
d0 = float(f[: inv["planning_horizon_days"]].mean())
sc = Scenario(price, promo, surge, lt, el)
r = simulate(
    d0,
    float(best.loc[cat, "rmse"]),
    a["unit_price"],
    a["unit_cost"],
    a["lead_time_days"],
    a["lead_time_sd_days"],
    sl,
    a["order_cost"],
    inv["holding_rate_annual"],
    sc,
    days=inv["planning_horizon_days"],
)

with right:
    m = st.columns(4)
    m[0].metric("Daily demand", f"{r.new_demand:.1f}", f"{r.new_demand - r.base_demand:+.1f}")
    m[1].metric(
        "Revenue (30 d)",
        fmt_money(r.new_revenue_30d),
        f"{(r.new_revenue_30d / r.base_revenue_30d - 1) * 100:+.1f}%" if r.base_revenue_30d else None,
    )
    m[2].metric(
        "Reorder point",
        f"{r.new_plan.reorder_point:,.0f}",
        f"{r.new_plan.reorder_point - r.base_plan.reorder_point:+,.0f}",
        delta_color="inverse",
        help="More units must be held before reordering.",
    )
    m[3].metric(
        "Safety stock",
        f"{r.new_plan.safety_stock:,.0f}",
        f"{r.new_plan.safety_stock - r.base_plan.safety_stock:+,.0f}",
        delta_color="inverse",
    )
    labels = ["Safety stock", "Reorder point", "EOQ", "Max stock"]
    base_v = [r.base_plan.safety_stock, r.base_plan.reorder_point, r.base_plan.eoq, r.base_plan.max_stock]
    new_v = [r.new_plan.safety_stock, r.new_plan.reorder_point, r.new_plan.eoq, r.new_plan.max_stock]
    fig = go.Figure()
    fig.add_bar(x=labels, y=base_v, name="Baseline", marker_color=PRIMARY)
    fig.add_bar(x=labels, y=new_v, name="Scenario", marker_color=ACCENT)
    fig.update_layout(barmode="group")
    st.plotly_chart(style_fig(fig, "Required stock levels (units)", 340), width="stretch")

    path = go.Figure()
    days = list(range(1, len(f[: inv["planning_horizon_days"]]) + 1))
    base_path = f[: inv["planning_horizon_days"]]
    mult = r.new_demand / r.base_demand if r.base_demand else 1
    path.add_scatter(x=days, y=base_path, name="Baseline forecast", line=dict(color=PRIMARY))
    path.add_scatter(x=days, y=base_path * mult, name="Scenario demand", line=dict(color=ACCENT, dash="dash"))
    path.update_xaxes(title="Days ahead")
    st.plotly_chart(style_fig(path, "Daily demand path (units)", 300), width="stretch")

st.markdown(
    f"**Interpretation:** under this scenario the planner should hold **{r.new_plan.reorder_point:,.0f}** units "
    f"before reordering (baseline {r.base_plan.reorder_point:,.0f}), with lead time "
    f"{r.new_lead_time:.0f} d (baseline {r.base_lead_time:.0f} d) at a {sl:.0%} service level. "
    f"Price {r.base_price:.2f} → {r.new_price:.2f} {cfg()['assumptions']['currency']}."
)
